/**
 * 读数怎么写成字。**全站唯一一处**（spec 2026-10-06 §6.3）。
 *
 * 这里做的事**不是计算**：四个页面拿到的都是后端算好的数，这一层只决定
 * 它印出来长什么样（硬约束 1：前端不做任何数值计算）。放在一处，是因为
 * 同一个 `1308` 在四页上必须是同一种写法 —— 四页各写一遍迟早会漂。
 */

/** `2026-07-23T11:00:00` → `2026-07-23 11:00`。ISO 里那个 T 不给人看，秒也不给。 */
export const fmtTime = (iso: string): string => iso.replace('T', ' ').slice(0, 16)

/** `1308`。不补千分位 —— 这是台仪器，不是一张财报。 */
export const fmtInt = (v: number): string => String(v)

/**
 * `43.2213` → `43.2`。**名字里不带「温度」**：页③ 的「无测量带」那一格拿它写
 * `z` 的上界，量纲是米。叫 `fmtTemp1` 会诱使人以为它只能用在温度上，
 * 于是那一格旁边迟早冒出一个 `toFixed`。
 *
 * 不收 `null`：收到 `null` 的地方（页② 的 MAE 那一格）走的是页② 自己的
 * `fmt`，那边「无值」要印成表格里的 `—`，与这里的小数不是同一种「没有」。
 */
export const fmt1 = (v: number): string => v.toFixed(1)

/** `38.9 至 48.8 °C`。区间用「至」—— 被禁的是 `—` 与 `→` 那类连接符（spec §8.5）。 */
export const fmtRange = (lo: number, hi: number, unit = ''): string =>
  `${fmt1(lo)} 至 ${fmt1(hi)}${unit ? ` ${unit}` : ''}`
